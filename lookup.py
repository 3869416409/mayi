def lookup(text):
    text = " " + text + " "
    hits = []
    for kws, skill, verdict in RULES:
        if any(kw in text for kw in kws):
            hits.append((skill, verdict))
    return hits


def main():
    if len(sys.argv) >= 2 and sys.argv[1] == "--file":
        if len(sys.argv) < 3:
            print("用法: python lookup.py --file feats.txt")
            return
        with open(sys.argv[2], "r", encoding="utf-8") as f:
            text = f.read().strip()
    elif len(sys.argv) >= 2:
        text = sys.argv[1]
    else:
        print("用法: python lookup.py \"特征文本\"  或  python lookup.py --file feats.txt")
        return
    hits = lookup(text)
    print("输入特征：", text)
    print("=" * 50)
    if not hits:
        print("未命中原书断语。可用维度示例：眉浓/眉淡/眼有神/鼻丰耸直/嘴角上扬/上停饱满/山根丰满 等。")
        return
    for skill, verdict in hits:
        print(f"[{skill}] {verdict}")


if __name__ == "__main__":
    main()
